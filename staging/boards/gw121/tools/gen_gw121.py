# Generates Gw121Hy3131Tables.h and Gw121Routes.h from a checkout of
# github.com/tpwrules/121gw-re and the range list below:
#
#   python3 -I gen_gw121.py <121gw-re checkout> ../inc
#
# The register images come from tables/hy_regtbl.h. Every row is checked
# against database/EEVBlog-102.c, the decompiled firmware, and generation
# stops on any difference.
import re, sys
repo, out = sys.argv[1], sys.argv[2]

src = open(repo + '/tables/hy_regtbl.h').read()
src = '\n'.join(l for l in src.splitlines() if not re.match(r'\s*//\s*[{0-9]', l))   # drop commented-out rows
dec = open(repo + '/database/EEVBlog-102.c', encoding='latin-1').read()
img = {}
for m in re.finditer(r'const uint8_t (hy_regtbl_\w+)(\[\d+\])?\[20\]\s*=\s*\{(.*?)\};', src, re.S):
    name, body = m.group(1), m.group(3)
    rows = [((r.group(1) or '').strip(), [int(x, 0) for x in r.group(2).split(',') if x.strip()])
            for r in re.finditer(r'(?://([^\n]*)\n\s*)?\{([^{}]*)\}', body)]
    if not rows:
        rows = [('', [int(x, 0) for x in body.split(',') if x.strip()])]
    d = re.search(r'_BYTE ' + name + r'(\[\d+\])?\[20\]\s*=\s*\{(.*?)\};', dec, re.S)
    dv = [int(x) & 0xFF for x in re.findall(r'-?\d+', re.sub(r'//[^\n]*', '', d.group(2)))]
    for i, (c, v) in enumerate(rows):
        if len(v) != 20 or dv[20 * i:20 * i + 20] != v:
            sys.exit('%s[%d] differs from the decompiled firmware' % (name, i))
        img[(name, i)] = (c, v)

def fl(x):
    t = '%.9g' % x
    return (t if ('.' in t or 'e' in t) else t + '.0') + 'f'

def cname(n, i):
    base = n.replace('hy_regtbl_', '')
    parts = base.split('_')
    s = 'k' + ''.join(p[:1].upper() + p[1:] for p in parts)
    return s + str(i)

