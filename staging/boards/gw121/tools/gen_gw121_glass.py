# Generates Gw121Glass.h, every named segment of the 121GW's LCD glass,
# from the segment enums in 121gw-re's IDA database export:
#
#   python3 -I gen_gw121_glass.py <121gw-re checkout> ../inc
#
# The enums LCD_SEGS_C<n><L|H> name the bits of the stock firmware's
# segment buffer: COM n, L = SEG0..31 (bit b = SEG b), H = SEG32..43 (bit b
# = SEG 32 + b). The buffer goes to LCD->RAM[2n] and RAM[2n + 1] as it is.
import re, sys
repo, out = sys.argv[1], sys.argv[2]
txt = open(repo + '/database/EEVBlog-102 - enumerations.txt', encoding='latin-1').read()
segs = []
cur = None
for line in txt.splitlines():
    m = re.search(r'enum LCD_SEGS_C([0-3])([LH])', line)
    if m:
        cur = (int(m.group(1)), m.group(2)); continue
    if 'enum ' in line:
        cur = None; continue
    m = re.match(r'[0-9A-F]+ (S[0-3][LH])_(\w+)\s+EQU (0x[0-9A-Fa-f]+|\d+)', line)
    if cur and m:
        com, half = cur
        assert m.group(1) == 'S%d%s' % (com, half), line
        v = int(m.group(3), 0)
        assert v and not (v & (v - 1)), line
        bit = v.bit_length() - 1
        segs.append((m.group(2), com, bit + (32 if half == 'H' else 0)))
names = [s[0] for s in segs]
assert len(names) == len(set(names)), 'a name twice'
assert len({(c, s) for _, c, s in segs}) == len(segs), 'a segment twice'
H = ['''/*
 * Gw121Glass.h  (generated by gen_gw121_glass.py: do not edit by hand)
 *
 *  The EEVblog 121GW's LCD glass: every segment the stock firmware names,
 *  as {COM, SEG} of the STM32L152's LCD controller. From the segment enums
 *  of 121gw-re's IDA database (LCD_SEGS_C0L .. C3H). %d segments.
 *
 *  Prefixes: MS main screen, SS sub screen, BG bargraph, ICON icons.
 *  Digits: <screen>_<place>_<stroke>, place 10000 (leftmost) .. 1.
 *  Points: <screen>_POINT_d0 is the point with one digit after it, d00 two, ...
 */

#ifndef GW121_GLASS_H_
#define GW121_GLASS_H_

#include "SegmentFrame.h"

namespace gw121 {
namespace glass {

using idisplay::SegRef;
''' % len(segs)]
for n, c, s in segs:
    H.append('inline constexpr SegRef %s{%d, %d};' % (n, c, s))
H.append('''
// All of them, for tests and a glass dump.
struct Named { const char* name; SegRef seg; };
inline constexpr Named kAll[] = {''')
for n, c, s in segs:
    H.append('\t{ "%s", %s },' % (n, n))
H.append('''};
inline constexpr unsigned kAllCount = sizeof(kAll) / sizeof(kAll[0]);

} // namespace glass
} // namespace gw121

#endif /* GW121_GLASS_H_ */
''')
open(out + '/Gw121Glass.h', 'w').write('\n'.join(H))
print('ok', len(segs), 'segments')
